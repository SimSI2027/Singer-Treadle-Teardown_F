local function clamp01(x) if x < 0 then return 0 elseif x > 1 then return 1 end return x end

-- easeInOutCubic / smoothstep / prog: the reference kit's sims/kit/util.js, ported verbatim
local function easeInOutCubic(x)
	local k = clamp01(x)
	if k < 0.5 then return 4 * k * k * k end
	local u = -2 * k + 2
	return 1 - u * u * u / 2
end
local function smoothstep(x) local k = clamp01(x) return k * k * (3 - 2 * k) end
local function prog(t, t0, t1) return easeInOutCubic((t - t0) / (t1 - t0)) end

local function V(t) return Vec(t[1], t[2], t[3]) end

-- cubic Bezier
local function bezier(p0, p1, p2, p3, u)
	local a = (1 - u) * (1 - u) * (1 - u)
	local b = 3 * (1 - u) * (1 - u) * u
	local c = 3 * (1 - u) * u * u
	local d = u * u * u
	return Vec(
		a * p0[1] + b * p1[1] + c * p2[1] + d * p3[1],
		a * p0[2] + b * p1[2] + c * p2[2] + d * p3[2],
		a * p0[3] + b * p1[3] + c * p2[3] + d * p3[3])
end

-- rotation by `deg` about `axis` through point p, as a local transform delta (body frame)
local function rotAbout(p, axis, deg)
	local q = QuatAxisAngle(axis, deg)
	return Transform(VecSub(p, QuatRotateVec(q, p)), q)
end

