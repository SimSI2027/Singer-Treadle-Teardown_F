local function exVec(t) return QuatRotateVec(ex.rootRot, V(t)) end
local function lin(t, t0, t1) return clamp01((t - t0) / (t1 - t0)) end

-- A withdrawal path: straight legs in the exhibit frame. Time is shared between legs in proportion
-- to their length and each leg is eased on its own, so the part comes to rest at every corner.
local function buildPath(legs)
	local path = {pts = {Vec(0, 0, 0)}, cum = {0}, total = 0, dir = Vec(0, 1, 0)}
	local acc = Vec(0, 0, 0)
	for _, leg in ipairs(legs) do
		local w = exVec(leg)
		local l = VecLength(w)
		if l > 0 then
			acc = VecAdd(acc, w)
			path.total = path.total + l
			path.pts[#path.pts + 1] = acc
			path.cum[#path.cum + 1] = path.total
			path.dir = VecScale(w, 1 / l)
		end
	end
	path.finish = acc
	return path
end

local function pathAt(path, u)
	if path.total <= 0 or u <= 0 then return Vec(0, 0, 0) end
	if u >= 1 then return path.finish end
	local d = u * path.total
	for i = 2, #path.pts do
		if d <= path.cum[i] then
			local k = (d - path.cum[i - 1]) / (path.cum[i] - path.cum[i - 1])
			return VecLerp(path.pts[i - 1], path.pts[i], easeInOutCubic(k))
		end
	end
	return path.finish
end

-- lift and shift windows depend on whether the selected subsystem is a frame
local function windows(rec)
