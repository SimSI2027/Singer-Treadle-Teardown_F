local function play(snd, vol)
	if snd ~= 0 then PlaySound(snd, ex.displayPos, vol) end
end

local function startOpen(id)
	st.mode, st.id, st.t, st.sway, st.yaw0 = "OPENING", id, 0, 0, 0
	play(ex.sndSlide, CONFIG.SLIDE_VOLUME)
end

local function startClose()
	if st.mode == "SHOWN" then
		st.yaw0 = CONFIG.SWAY_DEG * math.sin(st.sway * CONFIG.SWAY_RATE)
	end
	st.mode = "CLOSING"
	play(ex.sndSlide, CONFIG.SLIDE_VOLUME)
end

local function startRun()
	st.mode, st.id, st.t = "RUN", nil, 0
	runPrevStud = nil
end

-- one entry point for every button
local function press(id)
	if id == "reset" then
		st.queued = nil
		if st.mode == "OPENING" or st.mode == "SHOWN" then startClose() end
		return                                   -- CLOSING / RUN already end in IDLE
	end
	if st.mode == "IDLE" then
		if id == "run" then startRun() elseif ex.byId[id] and ex.byId[id].body ~= 0 then startOpen(id) end
	elseif st.mode == "SHOWN" then
		if id ~= st.id then st.queued = id end   -- close A, then open B (or RUN)
		startClose()
	end
	-- OPENING / CLOSING / RUN: ignored by design
end

local function step(dt)
	if st.mode == "OPENING" then
		st.t = st.t + dt
		if st.t >= CONFIG.OPEN_TIME then
			st.t = CONFIG.OPEN_TIME
			st.mode, st.sway = "SHOWN", 0
		end
		applyOpenPose(st.id, st.t, 0)
	elseif st.mode == "SHOWN" then
		st.sway = st.sway + dt
		applyOpenPose(st.id, CONFIG.OPEN_TIME, CONFIG.SWAY_DEG * math.sin(st.sway * CONFIG.SWAY_RATE))
	elseif st.mode == "CLOSING" then
		st.t = st.t - dt
		if st.t <= 0 then
			snapHome()
			st.mode, st.id, st.t, st.yaw0 = "IDLE", nil, 0, 0
			local q = st.queued
			st.queued = nil
			if q == "run" then startRun() elseif q then startOpen(q) end
		else
			applyOpenPose(st.id, st.t, st.yaw0)
		end
	elseif st.mode == "RUN" then
		st.t = st.t + dt
		if st.t >= CONFIG.RUN_TIME then
			snapHome()
			st.mode, st.t = "IDLE", 0
		else
			applyRunPose(runAngle(st.t))
		end
	end
end

