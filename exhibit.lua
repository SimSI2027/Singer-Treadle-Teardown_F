--[[
	Singer Treadle Sewing Machine: Interactive Exhibit
	==================================================

	A museum engineering exhibit for Teardown. Sixteen subsystems, one brass button each. Pressing a
	button lifts that subsystem clear, slides the rest of the machine aside as one rigid group, brings
	the subsystem forward to the display point and shows what it does. Everything is kinematic: static
	bodies moved with SetBodyTransform, every pose a pure function of an accumulated clock.

	Conventions (docs/CONVENTIONS.md):
	  * every pose is a function of time t; the same t gives the same pose (no randomness, no physics)
	  * CLOSING evaluates the OPENING function with t running backwards, then snaps to stored homes
	  * easing = easeInOutCubic / smoothstep only (formulas from the reference kit's util.js)
	  * find calls only in init(); one raycast per tick; nothing destructive, ever

	Layout of this file
	  1. CONFIG       every timing constant and tunable in one table
	  2. SUBSYSTEMS   every subsystem: id, name, exit path, display pose, articulation, exhibit text
	  3. GEOMETRY     generated by tools/generate.py (centres, pivots, kinematic constants)
	  4. math helpers + easing
	  5. pose functions (open/close, RUN)
	  6. state machine
	  7. Teardown callbacks: init / tick / draw

	Frames: "machine frame" = body-local frame of every subsystem body (x = visitor's right, y = up,
	z = toward the visitor). "Exhibit vectors" (exit, out, approach, offset) are expressed in the
	exhibit's own frame and rotated with it, so the exhibit works when spawned at any heading.
]]

