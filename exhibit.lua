function init()
	local function findLoc(role)
		for _, h in ipairs(FindLocations("anchor", false)) do
			if GetTagValue(h, "anchor") == role then return h end
		end
		return 0
	end
	local mA, sA, dA = findLoc("machine"), findLoc("shift"), findLoc("display")
	if mA == 0 or sA == 0 or dA == 0 then
		DebugPrint("singer exhibit: missing anchor location(s); exhibit disabled")
		return
	end
	ex.anchor = GetLocationTransform(mA)
	ex.shiftPos = GetLocationTransform(sA).pos
	ex.displayPos = GetLocationTransform(dA).pos
	ex.rootRot = ex.anchor.rot
	local upW = QuatRotateVec(ex.rootRot, Vec(0, 1, 0))

	local bodyOf = {}
	for _, h in ipairs(FindBodies("sys", false)) do
		bodyOf[GetTagValue(h, "sys")] = h
	end
	for _, def in ipairs(SUBSYSTEMS) do
		local h = bodyOf[def.id] or 0
		local rec = {id = def.id, def = def, body = h}
		if h ~= 0 then
			rec.home = GetBodyTransform(h)
			rec.localOffset = TransformToLocalTransform(ex.anchor, rec.home)
			rec.centerLocal = V(GEOM.center[def.id])
			rec.centerHome = TransformToParentPoint(rec.home, rec.centerLocal)
			rec.exitPath = buildPath(def.exit or {{0, 0.10, 0}})
			rec.makewayPath = buildPath(def.makeway or def.exit or {{0, 0.10, 0}})
			if def.out then
				rec.outW = exVec(def.out)
			else
				rec.outW = VecAdd(VecScale(rec.exitPath.dir, CONFIG.OUT_LEN), VecScale(upW, CONFIG.OUT_RISE))
			end
			rec.displayW = VecAdd(ex.displayPos, exVec(def.offset or {0, 0, 0}))
			rec.approachW = exVec(def.approach or CONFIG.APPROACH)
			local p = def.pose or {0, 0, 0}
			rec.displayRot = QuatRotateQuat(ex.rootRot, QuatEuler(p[1], p[2], p[3]))
			rec.upW = upW
		elseif CONFIG.DEBUG then
			DebugPrint("singer exhibit: no body for " .. def.id)
		end
		ex.byId[def.id] = rec
		ex.order[#ex.order + 1] = rec
	end

	for _, h in ipairs(FindShapes("btn", false)) do
		local id = GetTagValue(h, "btn")
		ex.buttons[h] = id
		ex.btnShape[id] = h
		SetShapeEmissiveScale(h, CONFIG.GLOW_IDLE)
		ex.glow[h] = CONFIG.GLOW_IDLE
	end
	for _, h in ipairs(FindShapes("art", false)) do
		local a = GetTagValue(h, "art")
		ex.art[a] = ex.art[a] or {}
		table.insert(ex.art[a], {shape = h, home = GetShapeLocalTransform(h)})
	end

	ex.sndClick = LoadSound("MOD/snd/click.ogg")
	ex.sndSlide = LoadSound("MOD/snd/slide.ogg")
	ex.ok = true
end

local function hoverButton()
	local cam = GetPlayerCameraTransform()
	local dir = TransformToParentVec(cam, Vec(0, 0, -1))
	local hit, _, _, shape = QueryRaycast(cam.pos, dir, CONFIG.RAY_DIST)
	if hit and shape ~= 0 then return ex.buttons[shape] end
	return nil
end

local function setGlow(h, v)
	if ex.glow[h] ~= v then
		SetShapeEmissiveScale(h, v)
		ex.glow[h] = v
	end
end

function tick(dt)
	if not ex.ok then return end
	st.hover = hoverButton()
	if st.hover then
		local h = ex.btnShape[st.hover]
		local c = CONFIG.OUTLINE
		DrawShapeOutline(h, c[1], c[2], c[3], c[4])
		if InputPressed("interact") then
			play(ex.sndClick, CONFIG.CLICK_VOLUME)
			press(st.hover)
		end
	end
	step(dt)
	-- one accent: only the button of the subsystem in motion / on show glows fully
	local active = st.id
	if st.mode == "RUN" then active = "run" end
	for h, id in pairs(ex.buttons) do
		local v = CONFIG.GLOW_IDLE
		if id == active then v = CONFIG.GLOW_ACTIVE elseif id == st.hover then v = CONFIG.GLOW_HOVER end
		setGlow(h, v)
	end
end

