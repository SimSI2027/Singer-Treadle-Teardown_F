-- (plus, in frame mode, the constant offset of the path it withdrew along to make way)
local function groupTransform(rec, s, makeway)
	local pos = VecLerp(ex.anchor.pos, ex.shiftPos, s)
	local t = TransformToParentTransform(Transform(pos, ex.anchor.rot), rec.localOffset)
	if makeway then t.pos = VecAdd(t.pos, makeway) end
	return t
end

-- the selected subsystem at timeline position t (0..OPEN_TIME), with sway yaw (degrees)
local function selectedTransform(rec, t, yaw)
	local l0, l1 = windows(rec)
	local pres = prog(t, CONFIG.PRESENT_START, CONFIG.PRESENT_END)
	local p
	if pres <= 0 then
		p = VecAdd(rec.centerHome, pathAt(rec.exitPath, lin(t, l0, l1)))
	else
		local lifted = VecAdd(rec.centerHome, rec.exitPath.finish)
		p = bezier(lifted, VecAdd(lifted, rec.outW), VecAdd(rec.displayW, rec.approachW), rec.displayW, pres)
	end
	local q = QuatSlerp(rec.home.rot, rec.displayRot, pres)
	if yaw ~= 0 then
		q = QuatRotateQuat(QuatAxisAngle(rec.upW, yaw * pres), q)
	end
	return Transform(VecSub(p, QuatRotateVec(q, rec.centerLocal)), q)
end

local function applyArticulation(rec, k)
	if not rec.def.art then return end
	for _, a in ipairs(rec.def.art) do
		local list = ex.art[a.art]
		if list then
			for _, item in ipairs(list) do
				local delta
				if a.deg then
					local pv = GEOM.kin[a.pivot] or PIVOTS[a.pivot] or {0, 0, 0}
					delta = rotAbout(V(pv), V(a.axis), a.deg * k)
				else
					delta = Transform(VecScale(V(a.move), k), Quat())
				end
				SetShapeLocalTransform(item.shape, TransformToParentTransform(delta, item.home))
			end
		end
	end
end

local function resetArticulation()
	for _, list in pairs(ex.art) do
		for _, item in ipairs(list) do
			SetShapeLocalTransform(item.shape, item.home)
		end
	end
end

-- pose the whole exhibit for OPENING/CLOSING/SHOWN at timeline t
local function applyOpenPose(id, t, yaw)
	local sel = ex.byId[id]
	local _, _, s0, s1 = windows(sel)
	local s = prog(t, s0, s1)
	local frame = sel.def.frame
	for _, rec in ipairs(ex.order) do
		if rec.body ~= 0 then
			if rec.id == id then
				SetBodyTransform(rec.body, selectedTransform(rec, t, yaw))
			else
				local off = nil
				if frame then
					local d = rec.def.makewayDelay or 0
					local m0 = CONFIG.LIFT_START + d * (CONFIG.LIFT_END - CONFIG.LIFT_START)
					off = pathAt(rec.makewayPath, lin(t, m0, CONFIG.LIFT_END))
				end
				SetBodyTransform(rec.body, groupTransform(rec, s, off))
			end
		end
	end
	applyArticulation(sel, prog(t, CONFIG.ARTICULATE_START, CONFIG.ARTICULATE_END))
end

local function snapHome()
	for _, rec in ipairs(ex.order) do
		if rec.body ~= 0 then SetBodyTransform(rec.body, rec.home) end
	end
	resetArticulation()
end

-- RUN: band-wheel angle (radians) from a trapezoidal speed profile, closed form
local function runAngle(t)
	local T, a = CONFIG.RUN_TIME, CONFIG.RUN_RAMP
	local total = 2 * math.pi * CONFIG.RUN_TURNS
	local w = total / (T - a)
	if t <= 0 then return 0 end
	if t >= T then return total end
	if t < a then return w * t * t / (2 * a) end
	if t < T - a then return w * a / 2 + w * (t - a) end
	local r = T - t
	return total - w * r * r / (2 * a)
end

-- treadle stud B on circle (P, Rs) with |A - B| = L; 2-D in the (z, y) plane; nearest to `prev`
local function solveStud(A, prev)
	local P = {GEOM.kin.treadle_pivot[3], GEOM.kin.treadle_pivot[2]}
	local r0, r1 = GEOM.kin.stud_r, GEOM.kin.pitman_len
	local dz, dy = A[1] - P[1], A[2] - P[2]
	local d = math.sqrt(dz * dz + dy * dy)
	local a = (r0 * r0 - r1 * r1 + d * d) / (2 * d)
	local h = math.sqrt(math.max(0, r0 * r0 - a * a))
	local mz, my = P[1] + a * dz / d, P[2] + a * dy / d
	local s1 = {mz + h * dy / d, my - h * dz / d}
	local s2 = {mz - h * dy / d, my + h * dz / d}
	local e1 = (s1[1] - prev[1]) ^ 2 + (s1[2] - prev[2]) ^ 2
	local e2 = (s2[1] - prev[1]) ^ 2 + (s2[2] - prev[2]) ^ 2
	if e1 <= e2 then return s1 end
	return s2
end

local function psi(z, y) return math.deg(math.atan2(y, z)) end

local runPrevStud = nil

-- pose the machine running at band-wheel angle theta (radians); every part from that one input
local function applyRunPose(theta)
	local K = GEOM.kin
	local X = Vec(1, 0, 0)
	local arm = theta * K.belt_ratio                       -- handwheel / arm shaft angle
	local thetaDeg, armDeg = math.deg(theta), math.deg(arm)

	-- band wheel (shape) and its crank pin
	local list = ex.art.band_wheel
	if list then
		for _, it in ipairs(list) do
			SetShapeLocalTransform(it.shape, TransformToParentTransform(rotAbout(V(K.band_axis), X, thetaDeg), it.home))
		end
	end
	-- rotation about +x by theta decreases the pin's (z, y) angle: psi = crank_phase - theta
	local Cz, Cy = K.band_axis[3], K.band_axis[2]
	local ang = K.crank_phase - theta
	local A = {Cz + K.crank_r * math.cos(ang), Cy + K.crank_r * math.sin(ang)}
	local A0 = {K.crank_pin0[3], K.crank_pin0[2]}
	local B0 = {K.stud0[3], K.stud0[2]}
	local B = solveStud(A, runPrevStud or B0)
	runPrevStud = B

	-- treadle: rotate about its pivot so the stud reaches B
	local P = {K.treadle_pivot[3], K.treadle_pivot[2]}
	local dT = psi(B0[1] - P[1], B0[2] - P[2]) - psi(B[1] - P[1], B[2] - P[2])
	local r = ex.byId.treadle
	if r and r.body ~= 0 then
		SetBodyTransform(r.body, TransformToParentTransform(r.home, rotAbout(V(K.treadle_pivot), X, dT)))
	end
	-- pitman: rigid motion taking (B0, A0) to (B, A)
	r = ex.byId.pitman_rod
	if r and r.body ~= 0 then
		local dP = psi(A0[1] - B0[1], A0[2] - B0[2]) - psi(A[1] - B[1], A[2] - B[2])
		local q = QuatAxisAngle(X, dP)
		local b0 = V(K.stud0)
		local b = Vec(K.stud0[1], B[2], B[1])
		SetBodyTransform(r.body, TransformToParentTransform(r.home, Transform(VecSub(b, QuatRotateVec(q, b0)), q)))
	end
	-- balance wheel and arm shaft turn together
	for _, id in ipairs({"drive_wheel", "crankshaft"}) do
		r = ex.byId[id]
		if r and r.body ~= 0 then
			SetBodyTransform(r.body, TransformToParentTransform(r.home, rotAbout(V(K.hand_axis), X, armDeg)))
		end
	end
	-- needle bar: top of stroke at arm angle 0
	r = ex.byId.needle_assembly
	if r and r.body ~= 0 then
		local dy = -K.needle_crank_r * (1 - math.cos(arm))
		SetBodyTransform(r.body, TransformToParentTransform(r.home, Transform(Vec(0, dy, 0), Quat())))
	end
	-- shuttle swings once per stitch
	list = ex.art.boat
	if list then
		local a = CONFIG.SHUTTLE_SWING_DEG * math.sin(arm)
		for _, it in ipairs(list) do
			SetShapeLocalTransform(it.shape, TransformToParentTransform(rotAbout(V(K.shuttle_pivot), X, a), it.home))
		end
	end
	-- feed dog: four-motion box cycle
	list = ex.art.feed_dog
	if list then
		local dz = -CONFIG.FEED_TRAVEL * 0.5 * math.cos(arm)
		local dy = CONFIG.FEED_LIFT * math.max(0, math.sin(arm))
		for _, it in ipairs(list) do
			SetShapeLocalTransform(it.shape, TransformToParentTransform(Transform(Vec(0, dy, dz), Quat()), it.home))
		end
	end
end

